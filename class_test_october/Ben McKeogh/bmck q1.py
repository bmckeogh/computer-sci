number = input("type a number")
number = float(number)
if number == 100:
    print("this number is equal to 100")
elif number > 100:
    print("this number is greater than 100")
elif number < 100:
    print("this number is less than 100")
elif number >= 100:
    print("this number is greater or equal to 100")
elif number <= 100:
    print("this number is less than or eqaul to 100")
elif number != 100:
    print("this number is not equal to 100")